// Run after `npx expo export -p web`:   node scripts/deploy-gen.mjs
// Embeds dist/ into one Cloudflare Worker module (static files + SPA fallback
// to index.html). Writes:
//   .deploy/worker.js            — the Worker source
//   .deploy/deploy-connector.js  — async function for the Cloudflare connector's execute tool
// Pattern follows cali-valley-bots/scripts/deploy-gen.mjs (no KV, no API routes).
import fs from "node:fs";
import path from "node:path";

const DIST = path.resolve("dist");
const OUT = path.resolve(".deploy");
const WORKER_NAME = "cali-valley-studios";
const COMPAT_DATE = "2026-10-01";
const MIME = {
  ".html": "text/html; charset=utf-8", ".js": "application/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8", ".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon",
  ".ttf": "font/ttf", ".otf": "font/otf", ".woff": "font/woff", ".woff2": "font/woff2", ".webmanifest": "application/manifest+json",
};

if (!fs.existsSync(DIST)) { console.error("dist/ missing — run npx expo export -p web first"); process.exit(1); }
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const files = {};
for (const f of walk(DIST)) {
  const rel = "/" + path.relative(DIST, f).split(path.sep).join("/");
  if (rel === "/metadata.json") continue;
  let buf = fs.readFileSync(f);
  if (rel === "/index.html") {
    // Paint the ground colour before JS loads (no white flash).
    buf = Buffer.from(buf.toString("utf8").replace("</head>", "<style>html,body{background:#0D0B10}</style></head>"));
  }
  files[rel] = { b64: buf.toString("base64"), ct: MIME[path.extname(rel).toLowerCase()] || "application/octet-stream" };
}

const workerSource = `// Auto-generated by scripts/deploy-gen.mjs — do not edit.
const FILES = ${JSON.stringify(files)};
const HDRS = { "X-Content-Type-Options": "nosniff", "Referrer-Policy": "strict-origin-when-cross-origin", "X-Robots-Tag": "noindex, nofollow" };
const cache = new Map();
function bodyOf(p) {
  if (!cache.has(p)) { const bin = atob(FILES[p].b64); const u = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i); cache.set(p, u); }
  return cache.get(p);
}
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== "GET" && request.method !== "HEAD") return new Response("Method Not Allowed", { status: 405 });
    let p = decodeURIComponent(url.pathname);
    if (p === "/") p = "/index.html";
    if (!FILES[p] && FILES[p + ".html"]) p = p + ".html";
    if (!FILES[p]) p = "/index.html"; // SPA fallback (Expo Router handles /design etc.)
    const h = new Headers(HDRS);
    h.set("content-type", FILES[p].ct);
    h.set("cache-control", p.startsWith("/_expo/") || p.startsWith("/assets/") ? "public, max-age=31536000, immutable" : "no-cache");
    return new Response(request.method === "HEAD" ? null : bodyOf(p), { status: 200, headers: h });
  },
};
`;

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, "worker.js"), workerSource);
const connector = `async () => {
  const name = ${JSON.stringify(WORKER_NAME)};
  const meta = { main_module: "worker.js", compatibility_date: ${JSON.stringify(COMPAT_DATE)} };
  const code = ${JSON.stringify(workerSource)};
  const form = new FormData();
  form.append("metadata", new Blob([JSON.stringify(meta)], { type: "application/json" }));
  form.append("worker.js", new Blob([code], { type: "application/javascript+module" }), "worker.js");
  const up = await cloudflare.request({ method: "PUT", path: \`/accounts/\${accountId}/workers/scripts/\${name}\`, body: form });
  const sd = await cloudflare.request({ method: "POST", path: \`/accounts/\${accountId}/workers/scripts/\${name}/subdomain\`, body: { enabled: true, previews_enabled: false } });
  return { uploaded: up.success, errors: up.errors, size: up.result && up.result.size, subdomain: sd.result, url: "https://" + name + ".travisleeswift.workers.dev" };
}`;
fs.writeFileSync(path.join(OUT, "deploy-connector.js"), connector);
console.log(JSON.stringify({ files: Object.keys(files).length, workerBytes: Buffer.byteLength(workerSource), connectorBytes: Buffer.byteLength(connector) }));
